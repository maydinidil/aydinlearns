-- pipeline/edge/olist_edge.sql (sprint 8 Part 2, S8-16; Task D1)
-- The hidden edge data for items on Olist (DS-RETAIL-01, schema olist): our own invented rows, never the dataset's, under the
-- prepared tables' names and with their columns and types (pipeline/datasets/olist.py). It holds no view and reads no other schema,
-- so it is built whether or not the real data is prepared. IDs are 32 hexadecimal characters, as the source's are: customer_id
-- c..., customer_unique_id a..., order_id b..., product_id f..., seller_id d..., review_id e.... As in the source, every order has
-- its own customer_id. The rows sit inside the registry questions' windows (orders of 2017, returns up to 31 August 2018), so a
-- query on DS-RETAIL-01-Q1's 2017 cohorts meets every plant. Planted:
--   a returning customer: a...01's first order is in March 2017, then July 2017 and February 2018, each under its own customer_id
--   (c...01, c...02, c...03), so a count on customer_id sees three one-time buyers;
--   a one-time buyer in the same March 2017 cohort (a...02);
--   an order at 23:50 on 31 January 2017 (a...05, January's cohort), delivered after its estimated delivery date;
--   an order with a missing delivery date that is not delivered: b...05 was shipped in May 2017 and never arrived;
--   a customer whose first order was canceled in April 2017 (b...06, with no approval, carrier or delivery date) and whose second,
--   in June 2017, was delivered (a...04);
--   two delivered orders on the same day, 12 September 2017 (a...06): no return on a later day;
--   a return after 31 August 2018 (a...07: November 2017, then 15 September 2018);
--   a first order in December 2016 and a second in February 2017 (a...08), so no 2017 cohort holds that customer;
--   an order paid in two payments, a voucher and a credit card, holding two items of the same product (b...02);
--   a product with a missing category, name length, description length and photo count (f...03), sold in September 2017;
--   a product whose category has no English name in the translation table (f...05), with freight above 30% of its price;
--   a review ID used twice, on two orders (e...05), and reviews with a missing title or comment.
-- Each order's payments add up to its items' prices and freight.
CREATE SCHEMA olist_edge;
CREATE TABLE olist_edge.customers (
  customer_id VARCHAR,
  customer_unique_id VARCHAR,
  customer_zip_code_prefix VARCHAR,
  customer_city VARCHAR,
  customer_state VARCHAR
);
CREATE TABLE olist_edge.orders (
  order_id VARCHAR,
  customer_id VARCHAR,
  order_status VARCHAR,
  order_purchase_timestamp TIMESTAMP,
  order_approved_at TIMESTAMP,
  order_delivered_carrier_date TIMESTAMP,
  order_delivered_customer_date TIMESTAMP,
  order_estimated_delivery_date TIMESTAMP
);
CREATE TABLE olist_edge.order_items (
  order_id VARCHAR,
  order_item_id INTEGER,
  product_id VARCHAR,
  seller_id VARCHAR,
  shipping_limit_date TIMESTAMP,
  price DOUBLE,
  freight_value DOUBLE
);
CREATE TABLE olist_edge.order_payments (
  order_id VARCHAR,
  payment_sequential INTEGER,
  payment_type VARCHAR,
  payment_installments INTEGER,
  payment_value DOUBLE
);
CREATE TABLE olist_edge.order_reviews (
  review_id VARCHAR,
  order_id VARCHAR,
  review_score INTEGER,
  review_comment_title VARCHAR,
  review_comment_message VARCHAR,
  review_creation_date TIMESTAMP,
  review_answer_timestamp TIMESTAMP
);
CREATE TABLE olist_edge.products (
  product_id VARCHAR,
  product_category_name VARCHAR,
  product_name_lenght INTEGER,
  product_description_lenght INTEGER,
  product_photos_qty INTEGER,
  product_weight_g INTEGER,
  product_length_cm INTEGER,
  product_height_cm INTEGER,
  product_width_cm INTEGER
);
CREATE TABLE olist_edge.sellers (
  seller_id VARCHAR,
  seller_zip_code_prefix VARCHAR,
  seller_city VARCHAR,
  seller_state VARCHAR
);
CREATE TABLE olist_edge.product_category_name_translation (
  product_category_name VARCHAR,
  product_category_name_english VARCHAR
);
